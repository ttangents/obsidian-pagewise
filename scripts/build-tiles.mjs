/**
 * Generates src/appearance/tiles.generated.ts from the WebP tiles in assets/tiles/:
 * one data URL per pattern and theme. The tiles travel in main.js and reach the
 * page as CSS custom properties on the elements that show a pattern
 * (src/appearance/patternStyle.ts), so styles.css stays small and Obsidian parses
 * the images only when a pattern shows.
 *
 * The tiles come from Home Cards (DECISIONS D3 and D16). The build fails, and
 * writes nothing, when a pattern lacks its light or dark tile.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const tilesDir = join(root, "assets", "tiles");
const out = join(root, "src", "appearance", "tiles.generated.ts");
const TILE = /^([a-z0-9]+)-(light|dark)\.webp$/;

const tiles = {};
for (const name of readdirSync(tilesDir).sort()) {
  const match = TILE.exec(name);
  if (!match) continue;
  const [, id, mode] = match;
  const data = readFileSync(join(tilesDir, name)).toString("base64");
  (tiles[id] ??= {})[mode] = `data:image/webp;base64,${data}`;
}
for (const [id, pair] of Object.entries(tiles)) {
  if (!pair.light || !pair.dark) {
    console.error(`build-tiles: ${id} needs both a light and a dark tile`);
    process.exit(1);
  }
}

const body = Object.entries(tiles)
  .map(([id, { light, dark }]) => `  ${id}: {\n    light: "${light}",\n    dark: "${dark}",\n  },`)
  .join("\n");
writeFileSync(
  out,
  `// Generated by scripts/build-tiles.mjs from assets/tiles/. Do not edit.\n\n/** Each pattern's tiles as data URLs, for light and dark themes. */\nexport const TILES: Readonly<Record<string, { readonly light: string; readonly dark: string }>> = {\n${body}\n};\n`
);
console.log(`build-tiles: ${Object.keys(tiles).length} patterns`);
